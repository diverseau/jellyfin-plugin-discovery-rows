const { chromium } = require('../work/browser/node_modules/playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; const providerCalls = []; const playbackCalls = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.url().includes('api.themoviedb.org')) providerCalls.push(r.url()); if (/Videos\//i.test(r.url())) playbackCalls.push(r.url()); });
  const base = process.env.DISCOVERY_FIXTURE_URL || 'http://127.0.0.1:18096';
  const auth = JSON.parse(fs.readFileSync('work/fixture/auth.json', 'utf8'));
  const headers = { 'X-Emby-Token': auth.admin.token, 'Content-Type': 'application/json' };
  const original = await (await fetch(base + '/Plugins/b87d3d47-7a2d-43c6-89d2-592885b90d3e/Configuration', {headers})).json();
  const testConfig = structuredClone(original); const empty = testConfig.Rows.find(r => r.Key === 'feelgood'); empty.Minimum = 16; empty.Limit = 16;
  await fetch(base + '/DiscoveryRows/Configuration', {method:'PUT',headers,body:JSON.stringify(testConfig)});
  try {
  await page.goto(base + '/web/index.html#/login');
  await page.waitForTimeout(1500);
  await page.locator('#txtManualName').fill('fixture-admin');
  await page.locator('#txtManualPassword').fill('Fixture-only-2026!');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL(/#\/home$/);
  await page.locator('.DiscoveryRowsUnder90Movies .card').first().waitFor();
  assert.equal(await page.locator('.DiscoveryRowsFeelGoodMovies:visible').count(), 0, 'Unsupported mood row must hide');
  await page.screenshot({ path: 'work/screenshots/homepage.png', fullPage: true });
  await page.goto(base + '/web/index.html#/configurationpage?name=discoveryrows');
  await page.waitForSelector('#drStatus .dr-stat');
  await page.screenshot({ path: 'work/screenshots/admin-setup.png', fullPage: true });
  await page.getByRole('button', { name: 'Shelves', exact: true }).click();
  assert.equal(await page.locator('#drRows .dr-row').count(), 38);
  await page.screenshot({ path: 'work/screenshots/admin-shelves.png', fullPage: true });
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.locator('#drPreviewUser').selectOption({ label: 'fixture-a' });
  await page.getByRole('button', { name: 'Inspect coverage' }).click();
  await page.waitForSelector('#drCoverage h3');
  assert.match(await page.locator('#drCoverage').innerText(), /eligible titles/);
  await page.screenshot({ path: 'work/screenshots/admin-preview.png', fullPage: true });
  await page.goto(base + '/web/index.html#/configurationpage?name=discoveryrows-preferences');
  await page.waitForSelector('#drPreferenceFind');
  await page.locator('#drPreferenceSearch').fill('Fixture Film 01');
  await page.locator('#drPreferenceFind').click();
  await page.waitForSelector('#drPreferenceLibrary button');
  await page.screenshot({ path: 'work/screenshots/preferences.png', fullPage: true });
  await page.goto(base + '/web/index.html#/home');
  await page.mouse.move(1100, 80);
  const card = page.locator('.DiscoveryRowsUnder90Movies .card .cardText').first();
  await card.waitFor(); await card.click();
  await page.waitForURL(/#\/details/);
  await page.screenshot({ path: 'work/screenshots/details.png', fullPage: true });
  await page.getByRole('button', { name: 'Play', exact: true }).first().click();
  await page.waitForFunction(() => { const v = document.querySelector('video'); return v && v.readyState >= 2; }, { timeout: 20000 });
  assert.ok(playbackCalls.length > 0, 'Native video stream requested');
  await page.screenshot({ path: 'work/screenshots/playback.png', fullPage: true });
  assert.equal(providerCalls.length, 0, 'Homepage/preview must not trigger provider calls');
  assert.deepEqual(errors, [], 'No browser runtime errors');
  fs.writeFileSync('work/browser-verification.json', JSON.stringify({ shelves: 38, emptyShelfHidden: true, nativeDetails: true, nativePlayback: true, providerCalls: providerCalls.length, errors }, null, 2));
  console.log('Browser checks passed: homepage, hidden empty shelf, 38 settings rows, preview, preferences, native details/playback, zero provider calls.');
  } finally { await fetch(base + '/DiscoveryRows/Configuration', {method:'PUT',headers,body:JSON.stringify(original)}); await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
